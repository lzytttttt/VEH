import type { LessonPlanChatInput, LessonPlanDraftInput } from './types';

/**
 * 教案演示脚本 — 教师角色常用教学模板
 * 覆盖 Word 基础排版（标题/加粗/斜体/列表/引用/表格/分割线/代码块）
 * 演示脚本聚焦"函数单调性"课题，与 microlesson 场景对齐便于联动
 */

export function buildLessonPlanLines(input: LessonPlanDraftInput): string[] {
  const topic = input.topic || '函数单调性判定';
  const subject = input.subject || '数学';
  const duration = input.duration ?? 45;
  return [
    `# ${topic} · 教案`,
    '',
    `> 学科：${subject}  ·  课时：${duration} 分钟  ·  学段：高三`,
    '',
    '## 一、教学目标',
    '1. 理解函数单调性的严格定义',
    '2. 掌握用导数判定单调性的方法',
    '3. 能求解常见函数的单调区间',
    '',
    '## 二、教学重难点',
    '- **重点**：导数判定法及步骤',
    '- **难点**：单调区间划分与驻点分析',
    '',
    '## 三、教学过程',
    '',
    '### 1. 情境导入（5 分钟）',
    '回顾函数图像随自变量增大的升降趋势，引出"单调性"概念。',
    '可借助动态图演示抛物线 y=x² 的升降变化。',
    '',
    '### 2. 新知讲解（20 分钟）',
    '**定义**：设 f(x) 在区间 I 上定义，对任意 x₁<x₂∈I，',
    '若 f(x₁)<f(x₂) 则递增；若 f(x₁)>f(x₂) 则递减。',
    '',
    "**判定法**：若 f(x) 在区间内可导，则 f'(x)>0 递增，f'(x)<0 递减。",
    '',
    '### 3. 例题精讲（12 分钟）',
    '**例 1**：f(x)=x²-2x+3，求单调区间。',
    "1. 求导 f'(x)=2x-2",
    "2. 令 f'(x)=0 得 x=1",
    '3. 划分区间 (-∞,1) 与 (1,+∞)',
    "4. 当 x<1 时 f'(x)<0 递减；x>1 时 f'(x)>0 递增",
    '',
    '### 4. 课堂练习（5 分钟）',
    '判断 f(x)=ln(x) 的单调性。',
    '> 提示：求 (ln x)\' 的符号',
    '',
    '### 5. 课堂小结（3 分钟）',
    '| 环节 | 要点 |',
    '|------|------|',
    '| 定义 | x₁<x₂ → f(x₁)<f(x₂) |',
    '| 判定 | f\'(x) 符号 |',
    '| 步骤 | 求导→驻点→分区→判号 |',
    '',
    '## 四、作业',
    '1. 教材 P82 第 1-3 题',
    '2. 拓展：判断 f(x)=x³ 的单调性',
    '',
    '---',
    '',
    '> 备注：下节课讲解函数极值与最值，请预习。',
  ];
}

export function matchLessonPlanChat(input: LessonPlanChatInput): string {
  const q = input.query.toLowerCase();
  if (/(导入|引入|情境)/.test(q)) {
    return '建议将"情境导入"环节扩展为：先用 GeoGebra 动态演示抛物线升降，让学生观察 2 分钟后回答"何时上升、何时下降"，再引出单调性概念。这样比单纯回顾图像更具启发性。';
  }
  if (/(例题|练习|题|变式)/.test(q)) {
    return '可在例题后追加一道变式：f(x)=x³-3x²+2 的单调区间。步骤相同（求导→驻点→分区→判号），但涉及两个驻点，能检验学生是否真正掌握"分区判号"思路。';
  }
  if (/(目标|重难点|重点|难点)/.test(q)) {
    return '建议把"难点"细化为：1) 驻点处单调性是否改变需单独验证；2) 区间端点开闭口的书写规范。可在讲解时强调这两个易错点。';
  }
  if (/(作业|拓展|分层)/.test(q)) {
    return '建议作业分层：基础层（P82 第 1-3 题）+ 提高层（判断 f(x)=x³ 单调性，需讨论驻点）+ 拓展层（研究三角函数单调性）。';
  }
  if (/(时间|节奏|分钟)/.test(q)) {
    return '当前节奏：导入5+新知20+例题12+练习5+小结3=45分钟。若学生基础较弱，建议把例题扩到15分钟、练习压缩到3分钟，并把"求导公式"单独复习2分钟。';
  }
  if (/(表格|小结|结构)/.test(q)) {
    return '小结环节建议用表格呈现"环节-要点"对照，比纯文字小结更清晰，便于学生回顾。已在本教案小结部分采用。';
  }
  return '已基于当前教案内容生成微调建议。你可以追问：导入环节怎么设计？例题能否加变式？作业如何分层？时间节奏如何调整？小结表格怎么写？';
}
